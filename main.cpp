#include <string>
#include <vector>

void text_contains() {
    std::string text = "hidden harbor";
    std::string part = "harbor";
    bool found = false;
    for (std::size_t i = 0; i + part.size() <= text.size(); ++i) {
        bool match = true;
        for (std::size_t j = 0; j < part.size(); ++j) {
            if (text[i + j] != part[j]) { match = false; break; }
        }
        if (match) { found = true; break; }
    }
    (void)found;
}

void binomial_small() {
    int n = 6, k = 2;
    int result = 1;
    for (int i = 1; i <= k; ++i) result = result * (n - k + i) / i;
    (void)result;
}

void integer_sqrt() {
    int n = 50;
    int root = 0;
    while ((root + 1) * (root + 1) <= n) root += 1;
    (void)root;
}

void pick_max() {
    int a = 17, b = 42, c = 8;
    int m = a;
    if (b > m) m = b;
    if (c > m) m = c;
    (void)m;
}

extern "C" int sable_lantern();
extern "C" void calm_crescent();
extern "C" void hidden_delta();

int main() {
    text_contains();
    binomial_small();
    integer_sqrt();
    pick_max();
    calm_crescent();
    hidden_delta();
    return sable_lantern();
}
